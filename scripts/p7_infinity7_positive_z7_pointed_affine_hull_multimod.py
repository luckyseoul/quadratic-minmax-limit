    require([len(rows) for rows in leaves_by_orbit] == [1_080, 1_080], "per-orbit leaf count changed")

    kernel_rows, hull_bases, hull_audit = build_hull_audit()
    anchors = AnchorFactory(kernel_rows, canonical_catalog(7, 4)[1:] - canonical_catalog(7, 4)[0])
