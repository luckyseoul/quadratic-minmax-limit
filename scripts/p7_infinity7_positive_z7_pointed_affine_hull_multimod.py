#!/usr/bin/env python3
"""Necessary mod-3/mod-7 affine-hull sieve for positive p=7, z=7.

This script reconstructs the two exact z=7 line orbits and all 2,160 exact
mean leaves.  It then applies both exhaustive pointed infinity-star branches:

* A: one line-star edge is present, normalized to (infinity, 0) = 1;
* B: all seven line-star edges vanish and one outside-star edge is present.

For every direction, an exact degree-two affine anchor with the prescribed
mean and parity is put into the right-hand side.  Every omitted catalog is
relaxed only to the anchor plus the complete degree-two, exact-zero-mean
space.  That space is generated by exact differences in the 56-row
``b=7, mean=4`` catalog and is independently proved to have the full expected
dimension modulo both 3 and 7.

Small and medium retained catalogs are enumerated once.  Their mod-3 and
mod-7 signatures are computed from the same catalog matrix in the same row
order and concatenated before joining, so a match cannot use one catalog row
modulo 3 and a different row modulo 7.  If there are more than two enumerable
directions, every retained pair is tested while all other variable directions
are relaxed to their affine hulls.

A zero-hit projection is a rigorous exclusion.  Passing is necessary only:
different retained-pair tests need not share a global catalog choice, affine
hulls can contain non-catalog points, and modular right-hand-side consistency
does not assert a binary edge lift.  Smoke mode rebuilds and audits the full
leaf universe but evaluates only a bounded representative subset and never
claims z=7 closure.
"""
