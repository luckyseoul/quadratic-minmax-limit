def prove_rho_min_f_from_bgf0(primes: list[int]) -> dict:
    rows = {}
    ok = True
    for p in primes:
        if p * p <= 5 and p != 3:
            if p * p == 5:
                continue
        if p == 3:
            # den uses p²-5=-4; formula 4(p⁴-1)/(3(p²-5)) still algebraically OK
            pass
        closed = rho_min_dot_f_if_bgf_zero(p)
        # from (4p bf + 4p bf)/den wait: (4p bf + Tbf)/den with Tbf=4p bf
        # = 8p bf / den, bf=2(p^4-1)/p, den=12(p²-5)
        bf = b_dot_f_formula(p)
        den = 12 * (p * p - 5)
        from_spec = Fraction(8 * p) * bf / den
        rows[str(p)] = {
            "closed": str(closed),
            "from_spectral": str(from_spec),
            "match": closed == from_spec,
        }
        if closed != from_spec:
            ok = False
    return {
        "proved": ok,
        "theorem": (
            "Under bgf=0: ⟨ρ_min,f_y⟩=4(p⁴−1)/(3(p²−5)) for all Max+ y."
        ),
        "by_p": rows,
    }


