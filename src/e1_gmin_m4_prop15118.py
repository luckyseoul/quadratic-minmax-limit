def kappa_gamma_f_formula(p: int) -> Fraction:
    """p(p²+1)(p²−1)(p²−4)/4."""
    return Fraction(p * (p * p + 1) * (p * p - 1) * (p * p - 4), 4)


def prove_kappa_gamma_f(primes: list[int]) -> dict:
    rows = {}
    ok = True
    for p in primes:
        n = n_of(p)
        closed = kappa_gamma_f_formula(p)
        alt = Fraction(n * p * (n - 2) * (n - 5), 4)
        # edge-expansion reconstruction (same algebra as derivation)
        E = n * (n - 1) // 2
        term1 = Fraction(E) * (Fraction(p * n, 2) - 2 * p) + Fraction(p * n, 2)
        term2 = Fraction((p * p + 1) * p * n, 2) - Fraction(p * n * (n - 1))
        from_edges = term1 + term2
        rows[str(p)] = {
            "closed": str(closed),
            "alt_n_form": str(alt),
            "from_edges": str(from_edges),
            "match": closed == alt == from_edges,
        }
        if not (closed == alt == from_edges):
            ok = False
    return {
        "proved": ok,
        "theorem": (
            "⟨κ,γ_y⊙f_y⟩=p(p²+1)(p²−1)(p²−4)/4 for all Max+ y, "
            "by edge expansion + Cy=py + C²=p²I."
        ),
        "by_p": rows,
    }


