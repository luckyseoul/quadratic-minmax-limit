def gamma_of(C, y, S):
    a, b, c, d = S
    return float(
        C[a, b] * y[a] * y[b]
        + C[a, c] * y[a] * y[c]
        + C[a, d] * y[a] * y[d]
        + C[b, c] * y[b] * y[c]
        + C[b, d] * y[b] * y[d]
        + C[c, d] * y[c] * y[d]
    )


def certify_pointwise(p: int) -> dict:
    Y = _load_Y(p)
    if Y is None:
        return {"p": p, "skipped": True}

    from minmax_quadratic import paley_conference_prime_power
    from scipy import sparse
    from scipy.sparse.linalg import lsqr

    C = paley_conference_prime_power(p).astype(np.float64)
    N, n = Y.shape
    quads = list(combinations(range(n), 4))
    nQ = len(quads)
    qindex = {q: i for i, q in enumerate(quads)}
    rows, cols, data = [], [], []
    for i, S in enumerate(quads):
        Sset = set(S)
        for v in S:
            others = tuple(sorted(x for x in S if x != v))
            for r in range(n):
                if r in Sset:
                    continue
                rows.append(i)
                cols.append(qindex[tuple(sorted(others + (r,)))])
                data.append(float(C[v, r]))
    T = sparse.csr_matrix((data, (rows, cols)), shape=(nQ, nQ))
    kap = np.array(
        [
            C[a, b] * C[c, d] + C[a, c] * C[b, d] + C[a, d] * C[b, c]
            for a, b, c, d in quads
        ],
        dtype=float,
    )
    bvec = T.dot(kap) / (p * p)
    T2kap = T.dot(T.dot(kap))
    A = sparse.eye(nQ) * (4 * p) - T
    rho_min = lsqr(A, bvec, atol=1e-14, btol=1e-14)[0]

    target_T2 = float(T2kappa_dot_m4_formula(p))
    pred_rmf = float(rho_min_dot_f_if_bgf_zero(p))
    pred_kgf = float(kappa_gamma_f_formula(p))
    pred_bf = float(b_dot_f_formula(p))

    bgf_max = 0.0
    T2_err = 0.0
    rmf_err = 0.0
    kgf_err = 0.0
    bf_err = 0.0
    for i in range(N):
        y = Y[i]
        fy = np.array(
            [y[a] * y[b] * y[c] * y[d] for a, b, c, d in quads], dtype=float
        )
        gam = np.array([gamma_of(C, y, S) for S in quads], dtype=float)
        gf = gam * fy
        bgf_max = max(bgf_max, abs(float(bvec @ gf)))
        T2_err = max(T2_err, abs(float(T2kap @ fy) - target_T2))
        rmf_err = max(rmf_err, abs(float(rho_min @ fy) - pred_rmf))
        kgf_err = max(kgf_err, abs(float(kap @ gf) - pred_kgf))
        bf_err = max(bf_err, abs(float(bvec @ fy) - pred_bf))

    # residual
    m4 = np.zeros(nQ)
    for i in range(N):
        y = Y[i]
        m4 += np.array(
            [y[a] * y[b] * y[c] * y[d] for a, b, c, d in quads], dtype=float
        )
    m4 /= N
    delta = m4 - kap / (p * p) - rho_min
    d2 = float(delta @ delta)
    hyp = float(room_hyp_over_24(p)) if p > 3 else 0.0

    return {
        "p": p,
        "N": N,
        "bgf_max_abs": bgf_max,
        "bgf_pointwise_zero": bgf_max < 1e-7,
        "T2kappa_f_max_err": T2_err,
        "T2kappa_f_constant_target": T2_err < 1e-3,
        "rho_min_f_max_err": rmf_err,
        "rho_min_f_closed": rmf_err < 1e-6,
        "kappa_gf_max_err": kgf_err,
        "kappa_gf_closed": kgf_err < 1e-4,
        "b_f_max_err": bf_err,
        "b_f_closed": bf_err < 1e-6,
        "delta2": d2,
        "room_hyp_24": hyp,
        "delta2_le_hyp": d2 <= hyp + 1e-6 if p > 3 else d2 < 1e-8,
        "target_T2": target_T2,
        "pred_rmf": pred_rmf,
        "pred_kgf": pred_kgf,
    }


