def T2kappa_dot_m4_formula(p: int) -> Fraction:
    """8 p² (p⁴ − 1)."""
    return Fraction(8 * p * p * (p**4 - 1))


def prove_T2kappa_m4(primes: list[int]) -> dict:
    rows = {}
    ok = True
    for p in primes:
        if p * p == 5:
            continue
        # from b2 path
        b2 = b2_of(p)
        den = 3 * (p * p - 5)
        from_b = Fraction(4 * (p**4) * b2, den)
        target = T2kappa_dot_m4_formula(p)
        # from n form before cancel
        n = n_of(p)
        from_n = Fraction(8 * n * (n - 1) * (n - 2) * (n - 6), p * p - 5)
        rows[str(p)] = {
            "from_b2": str(from_b),
            "from_n": str(from_n),
            "target_8p2_p4m1": str(target),
            "match": from_b == from_n == target,
        }
        if not (from_b == from_n == target):
            ok = False
    return {
        "proved": ok,
        "theorem": (
            "⟨T²κ,m₄⟩=8p²(p⁴−1) from Tκ∈E_±μ, δ⊥T²κ, balanced ρ_min split, "
            "‖b‖₂²=6n(n−1)(n−2)(n−6)/p⁴."
        ),
        "by_p": rows,
    }


