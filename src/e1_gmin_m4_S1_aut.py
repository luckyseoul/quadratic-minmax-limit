# ── Census: modular structure + Aut-constancy check ─────────────────────────

_G: dict = {}


def _init_C(C: np.ndarray) -> None:
    _G["C"] = C
    _blas1()


def _kappa(C, S) -> int:
    a, b, c, d = S
    return int(C[a, b] * C[c, d] + C[a, c] * C[b, d] + C[a, d] * C[b, c])


def _star(C, S, v) -> int:
    pr = 1
    for u in S:
        if u != v:
            pr *= int(C[v, u])
    return pr


def _shard(quads: list) -> dict:
    C = _G["C"]
    n = C.shape[0]
    d1 = d1_one(int(round(np.sqrt(n - 1))))
    n1 = 0
    n_const = 0
    stt_vals: Counter = Counter()
    formula_ok = 0
    formula_n = 0
    mod6_ok = 0
    for S in quads:
        if abs(_kappa(C, S)) != 1:
            continue
        n1 += 1
        S = tuple(S)
        stts = []
        for v in S:
            st = _star(C, S, v)
            others = tuple(x for x in S if x != v)
            t1 = 0
            A = 0
            nR1 = 0
            for rr in range(n):
                if rr in S:
                    continue
                Sp = tuple(sorted(others + (rr,)))
                kp = _kappa(C, Sp)
                if abs(kp) != 1:
                    continue
                nR1 += 1
                w = int(C[v, rr]) * kp
                t1 += w
                if w == 1:
                    A += 1
            # check t1 = 2A - d1 (d1 should equal nR1)
            formula_n += 1
            if nR1 == d1 and t1 == 2 * A - d1:
                formula_ok += 1
            stt = st * t1
            stts.append(stt)
            stt_vals[stt] += 1
            if stt % 6 == 5:
                mod6_ok += 1
        if len(set(stts)) == 1:
            n_const += 1
    return {
        "n1": n1,
        "n_const": n_const,
        "stt_vals": dict(stt_vals),
        "formula_ok": formula_ok,
        "formula_n": formula_n,
        "mod6_ok": mod6_ok,
    }


def certify_tau1_structure(p: int, W: int) -> dict:
    from minmax_quadratic import paley_conference_prime_power

    t0 = time.perf_counter()
    C = paley_conference_prime_power(p).astype(np.float64)
    quads = list(combinations(range(C.shape[0]), 4))
    nsh = min(W, max(1, len(quads) // 400))
    ss = (len(quads) + nsh - 1) // nsh
    shards = [quads[i : i + ss] for i in range(0, len(quads), ss)]
    n1 = n_const = 0
    stt_vals: Counter = Counter()
    formula_ok = formula_n = mod6_ok = 0
    with ProcessPoolExecutor(
        max_workers=min(W, len(shards)), initializer=_init_C, initargs=(C,)
    ) as ex:
        for fut in as_completed([ex.submit(_shard, sh) for sh in shards]):
            r = fut.result()
            n1 += r["n1"]
            n_const += r["n_const"]
            stt_vals.update(r["stt_vals"])
            formula_ok += r["formula_ok"]
            formula_n += r["formula_n"]
            mod6_ok += r["mod6_ok"]
    vals = sorted(stt_vals.keys())
    return {
        "p": int(p),
        "n_kappa1": n1,
        "star_tau1_constant_all_sets": n_const == n1,
        "star_tau1_values": vals,
        "n_distinct_values": len(vals),
        "n_distinct_expected_p_minus_1_over_2": (p - 1) // 2,
        "n_distinct_matches": len(vals) == (p - 1) // 2,
        "all_equiv_5_mod_6": all(v % 6 == 5 for v in vals),
        "all_odd": all(v % 2 == 1 for v in vals),
        "t1_eq_2A_minus_d1": formula_ok == formula_n,
        "formula_ok": formula_ok,
        "formula_n": formula_n,
        "mod6_ok_count": mod6_ok,
        "wall_s": float(time.perf_counter() - t0),
        "io": "ProcessPool pure-C; write_json_atomic",
    }


