        # d1=(3p²-7)/4: for odd p, 3p²-7 ≡ 3-7 ≡ -4 ≡ 0 mod 4, so d1 integer.
        # parity of d1: p=3 d1=5 odd; p=5 d1=17 odd; always odd for odd p?
