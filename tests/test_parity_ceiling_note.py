def test_witness_receipts_and_c102_exact_value():
    rows = json.loads((RECEIPTS / "witnesses.json").read_text())
    got = {}
    for row in rows:
        q = row["q"]
        C = pl.paley(q)
        x = _x(row["witness_x"])
        assert len(x) == q + 1
        Q = _q_exact(C, x)
        assert Q == row["witness_Q"] <= row["ceiling"]
        h = pl.fields(C, x)
        assert {str(int(v)): int(c) for v, c in zip(*np.unique(h, return_counts=True))} == row["fields"]
        got[q] = Q
    assert got == {61: 229, 73: 297, 89: 401, 97: 457, 101: 501, 109: 555, 113: 591}
    # order 102: the integral ceiling (no row identity needed) equals the witness value
    assert pc.ceiling(101, use_row_identity=False) == 501


