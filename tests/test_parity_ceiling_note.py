# Exact Paley values on file before this note (C10, C26, C50 are prime-power orders).
KNOWN_PALEY = {5: 5, 9: 15, 13: 21, 17: 33, 25: 65, 29: 75, 37: 109, 41: 129, 49: 175}


def _x(s: str) -> np.ndarray:
    return np.array([1 if ch == "+" else -1 for ch in s], dtype=np.int64)


def _q_exact(C: np.ndarray, x: np.ndarray) -> int:
    val = int(x @ C @ x)
    assert val % 2 == 0
    return val // 2


def test_fields_lie_in_one_class_mod_4_and_satisfy_the_row_identity():
    rng = np.random.default_rng(20261111)
    for q in (13, 29, 37, 61):
        C = pl.paley(q)
        n = q + 1
        assert (C @ C == q * np.eye(n, dtype=np.int64)).all()
        for _ in range(200):
            x = rng.choice([-1, 1], size=n)
            h = pl.fields(C, x)
            assert len(set((h % 4).tolist())) == 1
            assert int((h * h).sum()) == q * n
            D = C * np.outer(x, x)
            assert (D @ h == q).all()
            levels = {int(v): int(c) for v, c in zip(*np.unique(h, return_counts=True))}
            assert pc.row_identity_ok(levels, q)
            # flipping one coordinate moves every field to the other class
            y = x.copy()
            y[0] = -y[0]
            assert set((pl.fields(C, y) % 4).tolist()) == {(int(h[0]) + 2) % 4}


def test_ceiling_table_matches_receipt_and_known_exact_values():
    rows = json.loads((RECEIPTS / "ceilings.json").read_text())
    for row in rows:
        q = row["q"]
        if q > 120:
            continue  # the three large rows are regenerated by the script, not here
        assert pc.closed_form(q) == row["closed_form"]
        assert pc.ceiling(q, use_row_identity=False) == row["integral_ceiling"]
        assert pc.ceiling(q) == row["ceiling"]
        assert row["ceiling"] <= row["integral_ceiling"] <= row["closed_form"] <= row["spectral"]
    by_q = {r["q"]: r for r in rows}
    for q, val in KNOWN_PALEY.items():
        assert by_q[q]["ceiling"] == val
    assert by_q[53]["ceiling"] == 189 and by_q[101]["ceiling"] == 501


def test_order_54_hand_argument():
    """Reproduce Section 3's arithmetic: Q <= 189 for every symmetric conference matrix of order 54."""
    q, n = 53, 54
    # class 1: h = 5 + 4t, 5 T1 + 2 T2 = 189, T2 >= T1  =>  T1 <= 27, Q = 135 + 2 T1
    assert (q * n - 25 * n) == 8 * 189 and max(t1 for t1 in range(-n, n) if (189 - 5 * t1) % 2 == 0
                                                 and (189 - 5 * t1) // 2 >= abs(t1)) == 27
    # class 3: h = 7 + 4t, 7 T1 + 2 T2 = 27
    feas = []
    for t1 in range(-n, n):
        if (27 - 7 * t1) % 2:
            continue
        t2 = (27 - 7 * t1) // 2
        if t2 >= abs(t1) and (t2 - t1) % 2 == 0:
            feas.append((t1, t2))
    assert max(feas) == (3, 3) and sorted(feas)[-2][0] == -1
    # (3,3): fields 11 on three points, 7 elsewhere; row identity at a point with field 11 needs 77 + 4 s = 53
    assert all(77 + 4 * s != 53 for s in (-2, 0, 2))
    assert not pc.row_identity_ok({7: 51, 11: 3}, q)
    assert 189 + 2 * (-1) == 187


