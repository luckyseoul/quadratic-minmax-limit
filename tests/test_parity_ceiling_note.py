def test_torus_identity():
    for q in range(5, 200, 4):
        if not pl.is_prime(q):
            continue
        a, b = pl.two_squares(q)
        x, Q = tr.torus_witness(q)
        assert 2 * Q == (q + 1) * b
        assert set(pl.fields(pl.paley(q), x).tolist()) <= {b - a, b + a}
    receipt = json.loads((RECEIPTS / "torus.json").read_text())
    assert len(receipt["rows"]) == 80 and receipt["count_over_cap"] == 11
    by_q = {r["q"]: r for r in receipt["rows"]}
    assert by_q[173]["Q"] == 1131 and by_q[173]["ratio"] > math.sqrt(15) / 4


