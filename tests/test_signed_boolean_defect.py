def test_actual_paley_edge_sign_equals_its_unique_parallel_direction_sign():
    # This audits the precise source-sign convention used in Props 15.759--
    # 15.761.  Field elements are encoded as x+p*y, and the projective
    # functionals are x+lambda*y plus y at infinity.
    for p in (3, 5):
        conference = paley_conference_prime_power(p)
        directions = tuple((1, slope) for slope in range(p)) + ((0, 1),)
        epsilon = []
        for left, right in directions:
            kernel_representative = (
                1 if left == 0 else ((-right) % p) + p
            )
            epsilon.append(int(conference[1, 1 + kernel_representative]))

        parallel_directions = []
        tau = []
        for first, second in combinations(range(p * p), 2):
            x1, y1 = first % p, first // p
            x2, y2 = second % p, second // p
            parallel = [
                index
                for index, (left, right) in enumerate(directions)
                if (left * (x1 - x2) + right * (y1 - y2)) % p == 0
            ]
            assert len(parallel) == 1
            parallel_directions.append(parallel[0])
            tau.append(int(conference[1 + first, 1 + second]))
            assert tau[-1] == epsilon[parallel[0]]

        values = tuple((index % 7) - 3 for index in range(len(tau)))
        row = parallel_row_functional(parallel_directions, epsilon, values)
        assert row["induced_edge_signs_tau"] == tau
        assert row["weighted_parallel_total_H_y"] == row["tau_dot_z"]


def test_kernel_move_formula_drops_tau_term_exactly_when_tau_dot_g_is_zero():
    z = (1, -1, 1)
    tau = (1, 1, 1)
    for move in ((1, -3, 2), (-1, 3, -2)):
        row = kernel_move_defect_change(z, move, tau)
        assert row["proved"]
        assert row["tau_dot_move"] == 0
        expected = (
            2 * sum(a * b for a, b in zip(z, move))
            + sum(value * value for value in move)
        ) // 2
        assert row["defect_change"] == expected


