def test_nontrivial_complete_rank_one_graver_certificate_has_defect_one():
    # A=[[1,1,1],[0,2,3]], b=(1,1).  Its integer kernel is generated by
    # g=(1,-3,2), hence its Graver basis is exactly +/-g.  The displayed
    # lift solves Az=b.  A Boolean vector with first-row sum one would select
    # a single second-row entry from {0,2,3}, never 1.
    matrix = ((1, 1, 1), (0, 2, 3))
    target = (1, 1)
    z = (1, -1, 1)
    assert tuple(sum(row[j] * z[j] for j in range(3)) for row in matrix) == target
    audit = graver_voronoi_test(z, ((1, -3, 2), (-1, 3, -2)), (1, 1, 1))
    assert audit["defect"] == 1
    assert audit["no_supplied_move_improves"]
    assert [row["defect_change"] for row in audit["move_checks"]] == [13, 1]
    assert not audit["global_minimum_certified"]  # completeness is never guessed


def test_pointwise_pseudoinverse_and_residual_sign_formulas_agree_exactly():
    p = 7
    common_total = -23
    tau = -1
    epsilon_transverse = (1, -1, 1, 1, -1, -1, 1)
    normalized_cells = (2, -3, 5, 0, -4, 1, 6)
    actual_parallel_count = 9

    unsigned = moore_penrose_source_coordinate(
        p=p,
        common_total=common_total,
        parallel_target=tau * actual_parallel_count,
        transverse_target_cells=tuple(
            epsilon * value
            for epsilon, value in zip(epsilon_transverse, normalized_cells)
        ),
    )
    residual = residual_fractional_backprojection_coordinate(
        p=p,
        common_total=common_total,
        actual_parallel_count=actual_parallel_count,
        tau=tau,
        signed_backprojection_terms=tuple(
            tau * epsilon * value
            for epsilon, value in zip(epsilon_transverse, normalized_cells)
        ),
    )
    assert Fraction(residual["physical_fractional_coordinate_h_e"]) == (
        tau * Fraction(unsigned["R_plus_y_coordinate"])
    )
    assert residual["p_cubed_numerator"] == (
        tau * unsigned["p_cubed_numerator"]
    )
    assert residual["all_coordinates_in_interval_suffice_for_fractional_signed_box"]
    assert residual["necessity_not_claimed_because_real_kernel_shifts_are_available"]


def test_periodic_integer_dual_can_give_a_strict_no_boolean_certificate():
    # The equations fix z=(1,1,-1).  The first row is tau, so its target is
    # the fixed Boolean weight one, while the last two equations force two
    # selected coordinates.  Thus no Boolean vector is possible.  Here the
    # periodic integer dual is sharp at the displayed multiplier.
    matrix = ((1, 1, 1), (1, 0, 0), (0, 1, 0))
    target = (1, 1, 1)
    tau = (1, 1, 1)
    row = integer_lagrange_lower_bound(
        matrix, target, tau, (Fraction(-1), Fraction(1), Fraction(1))
    )
    assert Fraction(row["lower_bound"]) == 1
    assert Fraction(row["signed_box_farkas_slack"]) == 1
    assert row["periodic_bound_at_most_farkas_slack"]
    assert row["positive_bound_excludes_signed_boolean_lift"]
    assert row["no_integer_advantage_beyond_zonotope_separation"]


def test_periodic_dual_cannot_detect_an_integer_gap_inside_the_zonotope():
    # This is the rank-one-kernel Graver example above.  It has beta=1 and
    # no Boolean point, but x=(1/2,1/2,0) is a fractional box lift.  Therefore
    # every Farkas slack, and hence every periodic dual value, is <=0.
    matrix = ((1, 1, 1), (0, 2, 3))
    target = (1, 1)
    tau = (1, 1, 1)
    fractional = (Fraction(1, 2), Fraction(1, 2), Fraction(0))
    assert tuple(
        sum(Fraction(row[j]) * fractional[j] for j in range(3))
        for row in matrix
    ) == target
    for a in range(-8, 9):
        for b in range(-8, 9):
            row = integer_lagrange_lower_bound(
                matrix,
                target,
                tau,
                (Fraction(a, 4), Fraction(b, 4)),
            )
            assert Fraction(row["lower_bound"]) <= Fraction(
                row["signed_box_farkas_slack"]
            )
            assert Fraction(row["signed_box_farkas_slack"]) <= 0
            assert not row["positive_bound_excludes_signed_boolean_lift"]


