def test_coordinate_defect_is_nonnegative_and_has_exact_signed_boolean_roots():
    for tau in (-1, 1):
        for value in range(-30, 31):
            defect = signed_coordinate_defect(value, tau)
            assert defect >= 0
            assert (defect == 0) == (value in (0, tau))
    with pytest.raises(ValueError, match="sign"):
        signed_coordinate_defect(0, 0)


def test_vector_defect_has_the_exact_two_unit_norm_gap():
    tau = (1, -1, 1, -1)
    in_box = signed_boolean_defect((1, -1, 0, 0), tau)
    assert in_box["defect"] == 0
    assert in_box["squared_norm"] == in_box["tau_dot_z"] == 2
    assert in_box["in_signed_boolean_box"]

    outside = signed_boolean_defect((2, -1, 0, 0), tau)
    assert outside["defect"] == 1
    assert outside["squared_norm"] == outside["tau_dot_z"] + 2
    assert not outside["in_signed_boolean_box"]


